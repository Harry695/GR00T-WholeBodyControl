"""Generate obstacle scenes for the decoder-expressivity investigation.

Each scene is the stock ``scene_43dof.xml`` (G1 + Dex3 hands, floor, lights) plus static
obstacle geoms whose names start with ``obs_`` so loggers can detect robot/obstacle contact.
The robot spawns at the origin facing +x; obstacles sit ahead of it along +x.

Scenes are written next to scene_43dof.xml (the MJCF ``include`` and ``meshdir`` resolve
relative to the scene file), named ``scene_inv_<name>.xml``.

Usage:
    python make_scenes.py            # (re)generate all scenes
    python make_scenes.py --list     # print scene names
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

try:
    from .common import G1_MODEL_DIR
except ImportError:  # executed as a script
    from common import G1_MODEL_DIR

HEADER = """<mujoco model="g1_43dof {name}">
  <include file="g1_29dof_with_hand.xml"/>
  <!-- Auto-generated by gear_sonic/investigation/decoder_expressivity/make_scenes.py -->
  <!-- {description} -->

  <statistic center="1 0 0.5" extent="3.0"/>

  <visual>
    <headlight diffuse="0.6 0.6 0.6" ambient="0.3 0.3 0.3" specular="0 0 0"/>
    <rgba haze="0.15 0.25 0.35 1"/>
    <global azimuth="-130" elevation="-20"/>
  </visual>

  <asset>
    <texture type="skybox" builtin="gradient" rgb1="0.3 0.5 0.7" rgb2="0 0 0" width="512" height="3072"/>
    <texture type="2d" name="groundplane" builtin="checker" mark="edge" rgb1="0.2 0.3 0.4" rgb2="0.1 0.2 0.3"
      markrgb="0.8 0.8 0.8" width="300" height="300"/>
    <material name="groundplane" texture="groundplane" texuniform="true" texrepeat="5 5" reflectance="0.2"/>
    <material name="obstacle" rgba="0.85 0.45 0.15 1"/>
    <material name="obstacle_alt" rgba="0.75 0.75 0.2 1"/>
  </asset>

  <worldbody>
    <light pos="0 0 1.5" dir="0 0 -1" directional="true"/>
    <geom name="floor" size="0 0 0.05" type="plane" material="groundplane"/>
    <site name="com_marker" pos="0.1 0 0" size="0.05" rgba="1 0 0 1" type="sphere"/>
{obstacles}
  </worldbody>

  <default>
    <geom friction="1.0"/>
  </default>
</mujoco>
"""


def box(name, pos, half_size, material="obstacle"):
    p = " ".join(f"{v:.4f}" for v in pos)
    s = " ".join(f"{v:.4f}" for v in half_size)
    return f'    <geom name="obs_{name}" type="box" pos="{p}" size="{s}" material="{material}"/>'


def cylinder(name, pos, radius, half_height, material="obstacle_alt"):
    p = " ".join(f"{v:.4f}" for v in pos)
    return (f'    <geom name="obs_{name}" type="cylinder" pos="{p}" '
            f'size="{radius:.4f} {half_height:.4f}" material="{material}"/>')


# ----------------------------------------------------------------------------------------
# Scene definitions. Distances in metres, robot starts at x=0 facing +x.
# ----------------------------------------------------------------------------------------
HURDLE_X = 1.0
GAP_X = 1.2
BAR_X = 1.2


def hurdle(height):
    """A thin board across the path the robot must step over."""
    depth = 0.05
    return [box("hurdle", (HURDLE_X, 0.0, height / 2), (depth / 2, 0.75, height / 2))]


def gap(width):
    """A wall (perpendicular to +x) with an opening of `width` centred on y=0.

    Standing G1 is ~0.5 m across (arms included) facing forward and ~0.3 m deep,
    so narrow openings require turning sideways and shimmying.
    """
    thickness, height, extent = 0.30, 1.6, 1.2
    seg = (extent - width / 2) / 2
    yc = width / 2 + seg
    return [
        box("wall_left", (GAP_X, yc, height / 2), (thickness / 2, seg, height / 2)),
        box("wall_right", (GAP_X, -yc, height / 2), (thickness / 2, seg, height / 2)),
    ]


def lowbar(bottom_height):
    """A horizontal bar across the path; `bottom_height` is clearance under the bar.

    Standing G1 is ~1.32 m tall (head top), so bars below ~1.3 m force ducking,
    and below ~0.7 m force crawling.
    """
    bar_half_z = 0.03
    post_r = 0.03
    half_w = 0.9
    zc = bottom_height + bar_half_z
    return [
        box("bar", (BAR_X, 0.0, zc), (0.04, half_w, bar_half_z)),
        cylinder("post_left", (BAR_X, half_w, zc / 2), post_r, zc / 2),
        cylinder("post_right", (BAR_X, -half_w, zc / 2), post_r, zc / 2),
    ]


def clutter(seed, density=10, x_range=(0.6, 3.2), y_range=(-0.7, 0.7)):
    """Random small static objects on the floor (3-8 cm tall)."""
    rng = np.random.default_rng(seed)
    geoms = []
    for i in range(density):
        x = rng.uniform(*x_range)
        y = rng.uniform(*y_range)
        h = rng.uniform(0.03, 0.08)
        if rng.random() < 0.5:
            sx, sy = rng.uniform(0.03, 0.10, size=2)
            yaw_box = box(f"clutter_{i}", (x, y, h / 2), (sx, sy, h / 2))
            geoms.append(yaw_box)
        else:
            r = rng.uniform(0.03, 0.07)
            geoms.append(cylinder(f"clutter_{i}", (x, y, h / 2), r, h / 2))
    return geoms


SCENES = {}
for h_cm in (5, 10, 15, 20):
    SCENES[f"hurdle_{h_cm}cm"] = (hurdle(h_cm / 100), f"Hurdle {h_cm} cm tall at x={HURDLE_X} m")
for w_cm in (55, 40, 32):
    SCENES[f"gap_{w_cm}cm"] = (gap(w_cm / 100), f"Wall with a {w_cm} cm opening at x={GAP_X} m")
for h_cm in (120, 100, 85, 70, 55):
    SCENES[f"lowbar_{h_cm}cm"] = (lowbar(h_cm / 100), f"Overhead bar, {h_cm} cm clearance at x={BAR_X} m")
SCENES["clutter_sparse"] = (clutter(seed=0, density=8), "Sparse static floor clutter, seed 0")
SCENES["clutter_dense"] = (clutter(seed=1, density=20), "Dense static floor clutter, seed 1")


def scene_path(name: str) -> Path:
    if name in ("flat", "default", None):
        return G1_MODEL_DIR / "scene_43dof.xml"
    return G1_MODEL_DIR / f"scene_inv_{name}.xml"


def write_all(out_dir: Path = G1_MODEL_DIR) -> list[Path]:
    paths = []
    for name, (geoms, desc) in SCENES.items():
        xml = HEADER.format(name=name, description=desc, obstacles="\n".join(geoms))
        p = out_dir / f"scene_inv_{name}.xml"
        p.write_text(xml)
        paths.append(p)
    return paths


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--list", action="store_true", help="list scene names and exit")
    args = parser.parse_args()
    if args.list:
        for name, (_, desc) in SCENES.items():
            print(f"{name:18s} {desc}")
        return
    for p in write_all():
        print(f"wrote {p}")


if __name__ == "__main__":
    main()
